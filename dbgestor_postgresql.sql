DROP TABLE IF EXISTS asignaciones CASCADE;
DROP TABLE IF EXISTS comentarios CASCADE;
DROP TABLE IF EXISTS tareas CASCADE;
DROP TABLE IF EXISTS proyectos CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP SEQUENCE IF EXISTS hibernate_sequence CASCADE;


CREATE TABLE usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100),
    correo_electronico VARCHAR(100),
    contrasena VARCHAR(100),
    rol VARCHAR(100),
    imagen_usuario VARCHAR(255)
);


CREATE TABLE proyectos (
    id_proyecto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100),
    descripcion VARCHAR(100),
    fecha_inicio DATE,
    fecha_finalizacion DATE,
    estado_proyecto VARCHAR(100),
    fondo VARCHAR(100)
);


CREATE TABLE tareas (
    id_tarea INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100),
    descripcion VARCHAR(100),
    fecha_vencimiento DATE,
    estado VARCHAR(255),
    lista VARCHAR(255),
    id_proyecto INTEGER
);


CREATE TABLE comentarios (
    id_comentario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto_comentario VARCHAR(250),
    fecha_hora TIMESTAMP,
    id_usuario VARCHAR(100),
    id_tarea INTEGER
);


CREATE TABLE asignaciones (
    id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER,
    id_tarea INTEGER,
    fecha_asignacion DATE
);


CREATE SEQUENCE hibernate_sequence
START WITH 203
INCREMENT BY 1;


